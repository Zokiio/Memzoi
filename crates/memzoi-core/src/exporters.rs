#[cfg(test)]
pub fn export_okf(conn: &Connection, destination: &Path, scope: ScopeKind) -> Result<Vec<PathBuf>> {
    export_okf_at(conn, destination, scope, OffsetDateTime::now_utc())
}

pub(crate) fn export_okf_at(
    conn: &Connection,
    destination: &Path,
    scope: ScopeKind,
    now: OffsetDateTime,
) -> Result<Vec<PathBuf>> {
    let records = active_records_for_scope(conn, scope, None, now)?;
    export_records(conn, destination, &records)
}

